"""Write import files from redir/map.json into seo/redirects/ (run from the work dir)."""
import csv, json, re, sys
M = json.load(open("redir/map.json"))
OUT = sys.argv[1] if len(sys.argv) > 1 else "seo/redirects/"
TAG = sys.argv[2] if len(sys.argv) > 2 else "2026-11"
D = "https://marmarcandles.com"

def prio(m):
    if m["clicks"] >= 5 or m["impressions"] >= 300:
        return "A"
    if m["clicks"] >= 1 or m["impressions"] >= 30:
        return "B"
    return "C"

with open(f"{OUT}rankmath-redirects-{TAG}.csv", "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["source", "matching", "destination", "type", "category", "status", "ignore"])
    for m in M:
        w.writerow([m["source"].lstrip("/"), "exact", m["destination"], "301", f"mozello-{TAG}", "active", "case"])

lines = [f"# BEGIN MarMar Mozello redirects {TAG} (generated by tools/redirects, do not edit by hand)",
         "<IfModule mod_rewrite.c>", "RewriteEngine On"]
for m in M:
    p = m["source"].lstrip("/")
    if not re.fullmatch(r"[A-Za-z0-9_\-./]+", p):
        print("skip for htaccess (special chars):", m["source"])
        continue
    rx = re.sub(r"([.\\+*?\[^\]$(){}=!<>|:])", r"\\\1", p)
    lines.append(f"RewriteRule ^{rx}/?$ {m['destination']} [R=301,L,NC]")
lines += ["</IfModule>", f"# END MarMar Mozello redirects {TAG}"]
open(f"{OUT}htaccess-redirects-{TAG}.txt", "w").write("\n".join(lines) + "\n")

order = {"низкая": 0, "средняя": 1, "высокая": 2}
with open(f"{OUT}review-{TAG}.csv", "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["priority", "confidence", "source", "destination", "reason", "current_chain"])
    for m in sorted(M, key=lambda m: (prio(m), order[m["confidence"]])):
        w.writerow([prio(m), m["confidence"], m["source"], m["destination"].replace(D, ""), m["reason"], m["current"]])
print(len(M), "rules written")
